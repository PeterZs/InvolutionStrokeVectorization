import numpy as np
from scipy.ndimage import gaussian_filter1d
import sampler.hobbycurve as hobbycurve
from svgpathtools import Path, CubicBezier


def getpoints(path: Path, sampling=80):
    assert len(path) > 0
    if isinstance(sampling, int):
        sampling = np.linspace(0, 1, sampling+1)[1:]
    assert np.min(sampling) >0
    p = []
    for seg in path:
        complex_points = seg.points(sampling)
        points = np.column_stack((complex_points.real, complex_points.imag))
        p.append(points)
    
    return np.concat(p)

def standard_random_walk(n_steps, step_size=1.0):
    """
    Standard Brownian Motion.
    Steps are independent. Result is jagged.
    """
    # Generate random angles (0 to 2pi)
    thetas = np.random.uniform(0, 2*np.pi, n_steps)
    
    # Convert to xy steps
    dx = np.cos(thetas) * step_size
    dy = np.sin(thetas) * step_size
    
    # Cumulative sum to get positions
    x = np.cumsum(dx)
    y = np.cumsum(dy)
    return np.array([x, y]).T

def correlated_random_walk(n_steps, step_size=1.0, smoothness=0.1):
    """
    Correlated Random Walk (CRW).
    The angle changes by a small random amount each step.
    
    smoothness: Lower value = smoother (smaller angle changes).
                Higher value = more erratic.
    """
    # Start with an initial angle
    theta = np.zeros(n_steps)
    theta[0] = np.random.uniform(0, 2*np.pi)
    
    # Generate random angle changes (perturbations)
    # We clip the randomness to ensure we don't spin too wildly
    d_theta = np.random.normal(0, smoothness, n_steps)
    
    # Integrate angle changes
    theta = np.cumsum(d_theta)
    
    # Convert to steps
    dx = np.cos(theta) * step_size
    dy = np.sin(theta) * step_size
    
    x = np.cumsum(dx)
    y = np.cumsum(dy)
    return np.array([x, y]).T

def generate_layer(n_steps, sigma, amp):
    """
    Helper to generate a single smoothed random walk layer.
    """
    # 1. Generate standard Brownian motion
    raw_x = np.cumsum(np.random.normal(0, 1, n_steps))
    raw_y = np.cumsum(np.random.normal(0, 1, n_steps))
    
    # 2. Smooth it
    smooth_x = gaussian_filter1d(raw_x, sigma)
    smooth_y = gaussian_filter1d(raw_y, sigma)
    
    # 3. Normalize and scale to desired amplitude
    # (Normalization helps make the layers predictable relative to each other)
    smooth_x = (smooth_x - np.mean(smooth_x)) / np.std(smooth_x) * amp
    smooth_y = (smooth_y - np.mean(smooth_y)) / np.std(smooth_y) * amp
    
    return smooth_x, smooth_y


def fractal_random_walk(n_steps, octaves=[(80, 10.0), (20,1)], desired_dim=100, offset=None, scale = None):
    """
    Combines multiple layers of smoothed walks.
    octaves: A list of tuples (sigma, amplitude)
    """
    final_x = np.zeros(n_steps)
    final_y = np.zeros(n_steps)
    
    # Accumulate layers
    for sigma, amp in octaves:
        lx, ly = generate_layer(n_steps, sigma, amp)
        final_x += lx
        final_y += ly
        
    offset = np.sqrt(n_steps)
    box_size = 2*offset
    scale = desired_dim/box_size
        
    return (np.array([final_x, final_y]).T + offset)*scale

def hobby_to_path(points):
    """
    Converts a sequence of points generated by the hobby() function 
    into an svgpathtools.Path object.
    
    Parameters:
      - points: A numpy array or list of shape (N, 2) generated by hobby().
                The structure is expected to be [P0, C0a, C0b, P1, C1a, C1b, P2...].
    
    Returns:
      - svgpathtools.Path containing CubicBezier segments.
    """
    path = Path()
    
    # We step through the array 3 items at a time.
    # A single cubic segment is defined by 4 points:
    # Start (i), Control1 (i+1), Control2 (i+2), End (i+3)
    # The End point of one segment is the Start point of the next.
    for i in range(0, len(points) - 1, 3):
        start = complex(points[i][0], points[i][1])
        c1    = complex(points[i+1][0], points[i+1][1])
        c2    = complex(points[i+2][0], points[i+2][1])
        end   = complex(points[i+3][0], points[i+3][1])
        
        path.append(CubicBezier(start, c1, c2, end))
        
    return path


def hobby_walk(curvepoints, n_sampling: int| np.ndarray=80, omega=0.5):
    
    curves = hobbycurve.hobby(curvepoints, omega=omega)
    path = hobby_to_path(curves)
    return np.concat([curvepoints[:1],getpoints(path, n_sampling)])


def curvy_walk(n_steps, sampling_interval, n_sampling=80, step_size=1):
    p = standard_random_walk(n_steps, step_size)
    curvepoints= p[::sampling_interval]
    return hobby_walk(curvepoints, omega=0.5, n_sampling=n_sampling)


def densify_polyline_maxdist(polyline: np.ndarray, max_dist: float) -> np.ndarray:
    """
    Returns a densified polyline where every segment has length at most max_dist.
    Segments shorter than max_dist are left unchanged.

    Args:
        polyline: np.ndarray of shape (N, 2)
        max_dist: float, maximum allowed segment length

    Returns:
        np.ndarray of shape (M, 2) where M >= N
    """
    # 1. Handle edge cases
    if len(polyline) < 2:
        return polyline.copy()
    if max_dist <= 0:
        raise ValueError("max_dist must be positive")

    # 2. Calculate lengths of existing segments
    # shape: (N-1, 2)
    diffs = polyline[1:] - polyline[:-1]
    # shape: (N-1,)
    lengths = np.linalg.norm(diffs, axis=1)

    # 3. Determine how many segments each existing segment needs to be split into
    # We use ceil to ensure the new sub-segments are <= max_dist.
    # We enforce at least 1 segment (max with 1) to handle 0-length segments gracefully.
    num_segments = np.ceil(lengths / max_dist).astype(int)
    num_segments = np.maximum(num_segments, 1)

    # 4. Generate the new points
    new_points = []

    for i in range(len(num_segments)):
        p_start = polyline[i]
        p_end = polyline[i+1]
        n = num_segments[i]

        if n == 1:
            # If the segment is already short enough, keep the start point.
            # We treat the list as [start, end), appending the final end point later.
            new_points.append(p_start.reshape(1, 2))
        else:
            # Generate n+1 points (including start and end), then exclude the last one
            # so we don't duplicate points when moving to the next segment.
            # shape: (n, 2)
            segment_points = np.linspace(p_start, p_end, n + 1)[:-1]
            new_points.append(segment_points)

    # 5. Add the very last point of the original polyline
    new_points.append(polyline[-1].reshape(1, 2))

    # 6. Concatenate all parts
    return np.vstack(new_points)




def densify_polyline(polyline: np.ndarray, k: int) -> np.ndarray:
    """
    Adds k evenly spaced points between each segment of the polyline.
    
    Args:
        polyline: A (N, D) numpy array representing points (usually N, 2).
        k: The number of points to add per segment. 
           k=1 adds a point in the middle.
           
    Returns:
        A new polyline with shape ((N-1)*(k+1) + 1, D)
    """
    # 1. Handle edge cases
    if k <= 0:
        return polyline.copy()
    if len(polyline) < 2:
        return polyline.copy()

    polyline = np.asarray(polyline)
    
    # 2. Prepare the interpolation steps
    # We divide the segment into k + 1 sections.
    # steps shape: (k+1, ) -> e.g., [0.0, 0.33, 0.66] for k=2
    steps = np.linspace(0, 1, k + 2)[:-1]

    # 3. Calculate vector differences between points (segments)
    # shape: (N-1, D)
    starts = polyline[:-1]
    ends = polyline[1:]
    diffs = ends - starts

    # 4. Broadcasting to calculate new points
    # We expand dims to allow broadcasting:
    # starts: (N-1, 1, D)
    # steps:  (1, k+1, 1)
    # diffs:  (N-1, 1, D)
    # Result: (N-1, k+1, D)
    new_points = starts[:, None, :] + steps[None, :, None] * diffs[:, None, :]

    # 5. Flatten the segment and point dimensions
    # Shape becomes ((N-1)*(k+1), D)
    new_points = new_points.reshape(-1, polyline.shape[-1])

    # 6. Append the final point of the original polyline
    final_point = polyline[-1:] # Keep dims for vstack
    
    return np.vstack([new_points, final_point])


def densify_polyline_t(polyline: np.ndarray, t_values: list[float]) -> np.ndarray:
    """
    Inserts points at specific relative positions (t) within each segment.
    
    Args:
        polyline: (N, D) array of points.
        t_values: List of floats between 0 and 1 (e.g., [0.2, 0.5]). 
                  t=0 and t=1 are invalid and will be filtered out.
                  Values will be automatically sorted to preserve geometry.
                  
    Returns:
        New polyline with inserted points.
    """
    polyline = np.asarray(polyline)
    
    # 1. Edge case checks
    if len(polyline) < 2:
        return polyline.copy()
    
    # 2. Process t_values
    # Convert to array, filter out invalid values (<=0 or >=1), and sort them.
    # Sorting is critical: if input is [0.9, 0.1], we must process 0.1 before 0.9
    # or the line will zigzag.
    t_arr = np.sort(np.array(t_values, dtype=float))
    t_arr = t_arr[(t_arr > 0) & (t_arr < 1)]
    
    # If no valid t values exist, return original
    if len(t_arr) == 0:
        return polyline.copy()

    # 3. Create the computation grid
    # We prepend 0.0 to t_arr. 
    # This represents the Start Point of the segment (Original Point).
    # We do NOT append 1.0, because that is the Start Point of the *next* segment.
    steps = np.concatenate(([0.0], t_arr))
    
    # 4. Geometry setup
    starts = polyline[:-1]
    ends = polyline[1:]
    diffs = ends - starts
    
    # 5. Broadcasting
    # starts: (N-1, 1, D)
    # steps:  (1, M, 1)  -> where M is len(t_values) + 1
    # diffs:  (N-1, 1, D)
    # Result: (N-1, M, D)
    new_points = starts[:, None, :] + steps[None, :, None] * diffs[:, None, :]
    
    # 6. Flatten
    new_points = new_points.reshape(-1, polyline.shape[-1])
    
    # 7. Append the absolute final point of the original polyline
    final_point = polyline[-1:]
    
    return np.vstack([new_points, final_point])



class CubicBezierSequence:
    def __init__(self, points, tangents, tension=1.0/3.0):
        """
        points: (n, 2) array of knot points.
        tangents: (n, 2) or (n-2, 2) array of tangent vectors.
        tension: float, scalar to determine handle length relative to segment distance.
        """
        self.points = np.array(points)
        self.tension = tension
        self.n = len(self.points)
        
        # 1. Handle Tangent Logic (n vs n-2)
        tangents = np.array(tangents)
        if len(tangents) == self.n - 2:
            # We need to pad the start and end
            full_tangents = np.zeros((self.n, 2))
            full_tangents[1:-1] = tangents
            
            # Estimate start: direction from P0 to P1
            full_tangents[0] = self.points[1] - self.points[0]
            # Estimate end: direction from Pn-2 to Pn-1
            full_tangents[-1] = self.points[-1] - self.points[-2]
            
            self.tangents = full_tangents
        elif len(tangents) == self.n:
            self.tangents = tangents
        else:
            raise ValueError(f"Expected {self.n} or {self.n-2} tangents.")

        # 2. Normalize Tangents
        # We only want the direction. The magnitude is controlled by 'distance * tension'
        norms = np.linalg.norm(self.tangents, axis=1, keepdims=True)
        # Avoid division by zero
        norms[norms == 0] = 1.0 
        self.tangent_dirs = self.tangents / norms

    def get_control_points(self, idx):
        """
        Returns the 4 control points (P0, P1, P2, P3) for a specific segment index.
        Used internally or for visualization.
        """
        if idx < 0 or idx >= self.n - 1:
            raise ValueError(f"Segment index out of range (0 to {self.n-2})")
            
        # Anchors
        p0 = self.points[idx]
        p3 = self.points[idx+1]
        
        # Distance between anchors
        dist = np.linalg.norm(p3 - p0)
        
        # Handle Length
        handle_len = dist * self.tension
        
        # Directions
        # T0 is outgoing from P0
        t0 = self.tangent_dirs[idx]
        # T1 is incoming to P3. 
        # Since the stored tangent points "forward" along the global curve,
        # we subtract it to point the handle "backward" into the segment.
        t1 = self.tangent_dirs[idx+1]
        
        # Calculate Inner Control Points
        p1 = p0 + t0 * handle_len
        p2 = p3 - t1 * handle_len
        
        return p0, p1, p2, p3

    def get_points(self, segment_idx, u_array):
        """
        Batch sample points on a specific segment.
        segment_idx: int, which segment to sample
        u_array: np.array/list of floats between 0.0 and 1.0
        """
        u = np.array(u_array)
        
        # Get the 4 cubic bezier control points
        p0, p1, p2, p3 = self.get_control_points(segment_idx)
        
        # Prepare dimensions for broadcasting if u is an array
        # Reshape u to (k, 1) so it broadcasts against points (2,)
        if u.ndim == 1:
            u = u[:, np.newaxis]
            
        # Cubic Bezier Formula:
        # B(u) = (1-u)^3*P0 + 3(1-u)^2*u*P1 + 3(1-u)u^2*P2 + u^3*P3
        
        c0 = (1 - u)**3
        c1 = 3 * (1 - u)**2 * u
        c2 = 3 * (1 - u) * u**2
        c3 = u**3
        
        curve_points = c0*p0 + c1*p1 + c2*p2 + c3*p3
        return curve_points