def partition_graph_into_paths(G, max_path_len=None, min_cycle_len=3, max_cycles=None):
    """
    Decomposes the graph edges into a set of random paths/cycles such that 
    every edge is visited exactly once.

    Args:
        G: The NetworkX graph.
        max_path_len (int): The maximum number of vertices in a single path.
                            Defaults to total nodes if None.
        min_cycle_len (int): The minimum number of vertices required to form a cycle.
                             (e.g., 3 allows triangles).
        max_cycles (int): The maximum number of cycles allowed within a single path.
                          If None, unlimited cycles are allowed. 
                          If 0, paths will be strictly acyclic (simple paths).

    Returns:
        A list of paths, where each path is a list of coordinate tuples (x, y).
    """
    # Set default max length if not provided
    if max_path_len is None:
        max_path_len = G.number_of_nodes()

    # Work on a copy so we can destroy edges as we traverse them
    H = G.copy()

    paths_indices = []

    while H.number_of_edges() > 0:
        # Strategy: To maximize path coverage, prefer starting at nodes with ODD degree
        nodes_with_edges = [n for n, d in H.degree() if d > 0]
        odd_degree_nodes = [n for n in nodes_with_edges if H.degree(n) % 2 == 1]

        if odd_degree_nodes:
            current_node = random.choice(odd_degree_nodes)
        else:
            current_node = random.choice(nodes_with_edges)

        current_path_list = [current_node]
        # Dict for O(1) cycle checking: vertex -> last index encountered
        current_path_dict = {current_node: 0}
        current_cycle_count = 0

        while True:
            # Check Max Length constraint
            if len(current_path_list) >= max_path_len:
                break

            neighbors = list(H.neighbors(current_node))
            if not neighbors:
                break

            valid_neighbors = []
            next_idx = len(current_path_list)

            for n in neighbors:
                # Check if this neighbor creates a cycle (already in current path)
                is_cycle_move = n in current_path_dict

                if is_cycle_move:
                    # 1. Check Cycle Length Constraint
                    last_seen_idx = current_path_dict[n]
                    cycle_size = next_idx - last_seen_idx
                    if cycle_size < min_cycle_len:
                        continue # Cycle too tight, skip

                    # 2. Check Max Cycles Constraint
                    if max_cycles is not None and current_cycle_count >= max_cycles:
                        continue # Already hit limit, cannot add another cycle

                    valid_neighbors.append(n)
                else:
                    # Not a cycle, always valid (assuming standard path extension)
                    valid_neighbors.append(n)

            if not valid_neighbors:
                break

            # Pick a random valid next step
            next_node = random.choice(valid_neighbors)

            # If we picked a node that creates a cycle, increment counter
            if next_node in current_path_dict:
                current_cycle_count += 1

            # Remove the edge so it isn't visited again
            H.remove_edge(current_node, next_node)

            current_node = next_node

            # Update structures
            current_path_list.append(current_node)
            # Update the latest index for this node (allows for "figure-8" paths if cycles > 1)
            current_path_dict[current_node] = next_idx

        paths_indices.append(current_path_list)

    # Convert node indices to actual (x,y) coordinates


    return paths_indices


def compute_tangents_for_paths_simple(G: nx.Graph, paths_indices):
    """
    Computes normalized tangent vectors for each node in every path.

    Improvements:
    1. Neighbors are projected to unit distance from the center node to ensure
       tangent calculation is purely angular (unit circle chords).
    2. Nested paths (sharing a node without crossing) are grouped.
    3. Tangents of nested paths are averaged to guarantee a single tangent line 
       that respects the "opposite sides" topological constraint.
    4. Handles paths flowing in opposite directions via temporary inversion.

    Args:
        G: NetworkX graph with 'pos' attributes.
        paths_indices: List[List[int]] (node indices).

    Returns:
        List[List[Tuple[float, float]]]: Tangent vectors.
    """
    pos = nx.get_node_attributes(G, 'pos')

    # 1. Compute Individual Tangents (Projected to Unit Sphere)
    # Store tuples: (tangent_vector, incoming_unit_vec, outgoing_unit_vec)
    # incoming points TO node, outgoing points FROM node.
    path_data = []

    # Map node_idx -> list of (path_idx, seq_idx) for grouping later
    node_map = {n: [] for n in G.nodes()}

    for p_idx, path in enumerate(paths_indices):
        current_path_data = []
        n = len(path)
        for i, node_idx in enumerate(path):
            curr_p = np.array(pos[node_idx])

            # Identify neighbors
            prev_p = np.array(pos[path[i-1]]) if i > 0 else None
            next_p = np.array(pos[path[i+1]]) if i < n-1 else None

            # Compute Unit Vectors relative to center
            # u_vec points FROM Prev TO Curr (Incoming direction)
            # w_vec points FROM Curr TO Next (Outgoing direction)
            u_vec = np.zeros(2)
            w_vec = np.zeros(2)

            if prev_p is not None:
                diff = curr_p - prev_p
                norm = np.linalg.norm(diff)
                if norm > 1e-9:
                    u_vec = diff / norm

            if next_p is not None:
                diff = next_p - curr_p
                norm = np.linalg.norm(diff)
                if norm > 1e-9:
                    w_vec = diff / norm

            # Compute Tangent
            # For internal nodes, the tangent of the curve passing through unit neighbors
            # is the vector sum of the flow: (Outgoing Unit Vector) + (Incoming Unit Vector)
            # Note: u_vec is flow IN, w_vec is flow OUT.
            # Ideally, the tangent is the chord connecting Prev_Unit to Next_Unit.
            # Prev_Unit location relative to center is -u_vec. Next_Unit is +w_vec.
            # Chord = w_vec - (-u_vec) = w_vec + u_vec.

            if i == 0: # Start
                tangent = w_vec
            elif i == n - 1: # End
                tangent = u_vec
            else: # Internal
                tangent = u_vec + w_vec
                # Register for grouping logic
                node_map[node_idx].append((p_idx, i))

            # Normalize tangent
            t_norm = np.linalg.norm(tangent)
            if t_norm > 1e-9:
                tangent = tangent / t_norm
            else:
                # Fallback for sharp 180 turn or degenerate points
                # Use outgoing if available, else incoming
                tangent = w_vec if i < n-1 else u_vec

            current_path_data.append(tangent)

        path_data.append(current_path_data)

    # 2. Group Nested Paths and Average
    for v, segments in node_map.items():
        k = len(segments)
        if k < 2:
            continue

        center_pos = np.array(pos[v])

        # Build Adjacency Graph for Union-Find/DFS
        # Nodes: indices in 'segments'
        # Edge: if paths are nested (same side)
        # Flip: if paths flow in opposite directions
        adj = [[] for _ in range(k)]

        for i in range(k):
            for j in range(i + 1, k):
                p1, s1 = segments[i]
                p2, s2 = segments[j]

                # Retrieve neighbors for topology check
                # Note: s1-1 and s1+1 exist because we only mapped internal nodes
                path1 = paths_indices[p1]
                path2 = paths_indices[p2]

                u1 = np.array(pos[path1[s1-1]])
                w1 = np.array(pos[path1[s1+1]])
                u2 = np.array(pos[path2[s2-1]])
                w2 = np.array(pos[path2[s2+1]])

                # Topological Check (Circular Sort)
                # Vectors relative to center
                vecs = [u1-center_pos, w1-center_pos, u2-center_pos, w2-center_pos]
                angles = [(np.arctan2(vec[1], vec[0]), idx) for idx, vec in enumerate(vecs)]
                angles.sort(key=lambda x: x[0])

                order = [x[1] for x in angles]
                # Labels: 0,1 are Path A; 2,3 are Path B
                s_order = "".join(['A' if o < 2 else 'B' for o in order])

                # If NOT alternating (ABAB), they are nested/disjoint
                if s_order not in ["ABAB", "BABA"]:
                    # Check relative direction using dot product of initial tangents
                    t1 = path_data[p1][s1]
                    t2 = path_data[p2][s2]
                    dot = np.dot(t1, t2)

                    must_flip = (dot < 0)
                    adj[i].append((j, must_flip))
                    adj[j].append((i, must_flip))

        # 3. Process Components
        visited = [False] * k
        for i in range(k):
            if not visited[i]:
                component_stack = [(i, False)] # (index, is_flipped)
                visited[i] = True

                comp_indices = []
                comp_states = {} # idx -> is_flipped

                # Collect all vectors in this nested group
                vectors_sum = np.zeros(2)

                while component_stack:
                    curr, flipped = component_stack.pop()
                    comp_indices.append(curr)
                    comp_states[curr] = flipped

                    p_idx, s_idx = segments[curr]
                    vec = path_data[p_idx][s_idx]

                    if flipped:
                        vectors_sum -= vec
                    else:
                        vectors_sum += vec

                    for neighbor, edge_flip in adj[curr]:
                        if not visited[neighbor]:
                            visited[neighbor] = True
                            new_flip = flipped ^ edge_flip
                            component_stack.append((neighbor, new_flip))

                # Compute Average Tangent
                avg_norm = np.linalg.norm(vectors_sum)
                if avg_norm > 1e-9:
                    final_tangent = vectors_sum / avg_norm

                    # Apply back to paths
                    for idx in comp_indices:
                        p_idx, s_idx = segments[idx]
                        flipped = comp_states[idx]

                        # If the path was processed as flipped, its tangent is -Average
                        # If processed as normal, its tangent is +Average
                        t = -final_tangent if flipped else final_tangent
                        path_data[p_idx][s_idx] = t

    # Convert to simple list of tuples
    result = []
    for p_vecs in path_data:
        result.append([tuple(v) for v in p_vecs])

    return result


def rotate_away(v: np.ndarray, from_: np.ndarray, w: float) -> np.ndarray:
    """
    Rotate 2D vector v away from vector `from_`.

    w = 0 → no rotation (returns v)
    w = 1 → points exactly opposite to `from_`
    """

    if not (0.0 <= w <= 1.0):
        raise ValueError("w must be in [0, 1]")

    # Normalize inputs
    v_hat = v / np.linalg.norm(v)
    from_hat = from_ / np.linalg.norm(from_)

    # Target direction is opposite of `from`
    target = -from_hat

    # Compute angle between v_hat and target
    dot = np.clip(np.dot(v_hat, target), -1.0, 1.0)
    theta = np.arccos(dot)

    # If already aligned or opposite, no rotation needed
    if theta < 1e-8:
        return v_hat * np.linalg.norm(v)

    # Determine rotation direction (sign)
    cross = v_hat[0] * target[1] - v_hat[1] * target[0]
    sign = np.sign(cross)

    # Interpolated rotation angle
    angle = sign * w * theta

    # Rotation matrix
    c, s = np.cos(angle), np.sin(angle)
    R = np.array([[c, -s],
                  [s,  c]])

    # Rotate and restore original magnitude
    return R @ v_hat * np.linalg.norm(v)


def angle_interp(bisector: np.ndarray, max_radians: float, value: float) -> np.ndarray:
    """
    Interpolate a 2D vector around the angle of `bisector`.

    Parameters
    ----------
    bisector : np.ndarray
        2D vector defining the central direction.
    max_radians : float
        Maximum angular deviation (in radians) from the bisector.
    value : float
        Interpolation value where:
          - value = -0.5 -> angle(bisector) - max_radians
          - value =  0.0 -> angle(bisector)
          - value = +0.5 -> angle(bisector) + max_radians

    Returns
    -------
    np.ndarray
        Rotated 2D vector.
    """
    if bisector.shape != (2,):
        raise ValueError("bisector must be a 2D vector")

    # Base angle and magnitude
    base_angle = np.arctan2(bisector[1], bisector[0])
    magnitude = np.linalg.norm(bisector)

    # Map value ∈ [-0.5, 0.5] to angle offset ∈ [-max_radians, +max_radians]
    angle_offset = 2.0 * value * max_radians
    new_angle = base_angle + angle_offset

    return magnitude * np.array([
        np.cos(new_angle),
        np.sin(new_angle),
    ])


def get_random_partition(start, stop, n, min_len=0):
    """
    Partitions the float interval [start, stop] into n random intervals.

    Args:
        start (float): The starting value of the interval.
        stop (float): The ending value of the interval.
        n (int): The number of desired intervals.
        min_len (float): The minimum length of each interval.

    Returns:
        list: A list of n floats representing the start of each interval. 
              The first value is always 'start'.

    Raises:
        ValueError: If the total interval length is insufficient for n * min_len.
    """
    if n < 1:
        raise ValueError("Number of intervals (n) must be at least 1.")

    width = stop - start
    required_width = n * min_len

    if required_width > width:
        raise ValueError(f"Total interval width ({width}) is too small for "
                         f"{n} intervals of minimum length {min_len}.")

    # Calculate the "slack" (the length available to be randomized)
    slack = width - required_width

    # Generate n-1 random points within the slack and sort them.
    # We add 0.0 at the start to represent the beginning of the slack allocation.
    slack_cuts = [0.0] + sorted(random.uniform(0, slack) for _ in range(n - 1))

    # Calculate the actual coordinates.
    # Formula: start + (random_slack_point) + (index * fixed_min_len_bias)
    partition_points = [
        start + cut + (i * min_len)
        for i, cut in enumerate(slack_cuts)
    ]

    return partition_points


def compute_tangents_for_paths_all_tangent(G: nx.Graph, paths_indices, terminal_angles_strategy: str='random'):
    """
    Computes normalized tangent vectors for each node in every path.

    Improvements:
    1. Neighbors are projected to unit distance from the center node.
    2. Nested paths (sharing a node without crossing) are grouped and averaged.
    3. Terminal Path Logic: 
       - Inserts terminal paths into the angular order of neighbors.
       - Interpolates tangent based on containment within neighbor triangles.
    """
    pos = nx.get_node_attributes(G, 'pos')

    # --- 1. Compute Individual Tangents (Projected to Unit Sphere) ---
    path_data = []

    # Map node_idx -> list of (path_idx, seq_idx)
    node_map = {n: [] for n in G.nodes()}

    for p_idx, path in enumerate(paths_indices):
        current_path_data = []
        n = len(path)
        for i, node_idx in enumerate(path):
            curr_p = np.array(pos[node_idx])

            # Identify neighbors for flow calculation
            prev_p = np.array(pos[path[i-1]]) if i > 0 else None
            next_p = np.array(pos[path[i+1]]) if i < n-1 else None

            u_vec = np.zeros(2) # Incoming (Prev -> Curr)
            w_vec = np.zeros(2) # Outgoing (Curr -> Next)

            if prev_p is not None:
                diff = curr_p - prev_p
                norm = np.linalg.norm(diff)
                if norm > 1e-9: u_vec = diff / norm

            if next_p is not None:
                diff = next_p - curr_p
                norm = np.linalg.norm(diff)
                if norm > 1e-9: w_vec = diff / norm

            # Initial Tangent Calculation
            # Start: Points to Next. End: Points from Prev. Internal: Average.
            if i == 0:
                tangent = w_vec
            elif i == n - 1:
                tangent = u_vec
            else:
                tangent = u_vec + w_vec

            # Normalize tangent
            t_norm = np.linalg.norm(tangent)
            if t_norm > 1e-9:
                tangent = tangent / t_norm
            else:
                tangent = w_vec if i < n-1 else u_vec

            node_map[node_idx].append((p_idx, i))
            current_path_data.append(tangent)

        path_data.append(current_path_data)

    # --- 2. Process Intersections (Grouping Nested Paths) ---
    # Note: We skip terminal logic here and handle it strictly after grouping
    for v, segments in node_map.items():
        k = len(segments)
        if k < 2:
            continue

        center_pos = np.array(pos[v])

        # Build Adjacency Graph for Union-Find/DFS for Internal Nodes
        adj = [[] for _ in range(k)]

        for i in range(k):
            for j in range(i + 1, k):
                p1, s1 = segments[i]
                p2, s2 = segments[j]

                path1 = paths_indices[p1]
                path2 = paths_indices[p2]
                n1, n2 = len(path1), len(path2)

                # Only group if both are internal nodes (Strict Grouping Phase)
                if (0 < s1 < n1 - 1) and (0 < s2 < n2 - 1):
                    u1 = np.array(pos[path1[s1-1]])
                    w1 = np.array(pos[path1[s1+1]])
                    u2 = np.array(pos[path2[s2-1]])
                    w2 = np.array(pos[path2[s2+1]])

                    vecs = [u1-center_pos, w1-center_pos, u2-center_pos, w2-center_pos]
                    angles = [(np.arctan2(vec[1], vec[0]), idx) for idx, vec in enumerate(vecs)]
                    angles.sort(key=lambda x: x[0])

                    order = [x[1] for x in angles]
                    s_order = "".join(['A' if o < 2 else 'B' for o in order])

                    if s_order not in ["ABAB", "BABA"]:
                        t1 = path_data[p1][s1]
                        t2 = path_data[p2][s2]
                        dot = np.dot(t1, t2)
                        must_flip = (dot < 0)
                        adj[i].append((j, must_flip))
                        adj[j].append((i, must_flip))

        # Process Components (Averaging)
        visited = [False] * k
        for i in range(k):
            p_curr, s_curr = segments[i]
            n_curr = len(paths_indices[p_curr])
            # Skip terminals in this phase
            if not (0 < s_curr < n_curr - 1):
                continue

            if not visited[i]:
                component_stack = [(i, False)]
                visited[i] = True

                comp_indices = []
                comp_states = {}
                vectors_sum = np.zeros(2)

                while component_stack:
                    curr, flipped = component_stack.pop()
                    comp_indices.append(curr)
                    comp_states[curr] = flipped

                    p_idx, s_idx = segments[curr]
                    vec = path_data[p_idx][s_idx]

                    if flipped:
                        vectors_sum -= vec
                    else:
                        vectors_sum += vec

                    for neighbor, edge_flip in adj[curr]:
                        if not visited[neighbor]:
                            visited[neighbor] = True
                            new_flip = flipped ^ edge_flip
                            component_stack.append((neighbor, new_flip))

                avg_norm = np.linalg.norm(vectors_sum)
                if avg_norm > 1e-9:
                    final_tangent = vectors_sum / avg_norm
                    for idx in comp_indices:
                        p_idx, s_idx = segments[idx]
                        flipped = comp_states[idx]
                        t = -final_tangent if flipped else final_tangent
                        path_data[p_idx][s_idx] = t

    # --- 3. Process Terminal Paths (The New Logic) ---
    for v, segments in node_map.items():
        center_pos = np.array(pos[v])

        # Identify terminals and non-terminals
        terminals = []
        throughs = []

        for idx, (p_idx, s_idx) in enumerate(segments):
            n_len = len(paths_indices[p_idx])
            if s_idx == 0 or s_idx == n_len - 1:
                terminals.append((p_idx, s_idx))
            else:
                throughs.append((p_idx, s_idx))

        if not terminals:
            continue

        # Build Tangent Circle (All Natural Outward Vectors)
        # Entry: (angle, is_terminal, vector_val, path_idx, s_idx)
        circle_entries = []

        # 3a. Add Through-Path Vectors
        # A through path has TWO outward vectors: to prev and to next.
        # We need to map which leg corresponds to which direction of the COMPUTED tangent.
        for p_idx, s_idx in throughs:
            path = paths_indices[p_idx]

            # Leg to Prev
            v_prev = np.array(pos[path[s_idx-1]]) - center_pos
            v_prev = v_prev / (np.linalg.norm(v_prev) + 1e-9)
            ang_prev = np.arctan2(v_prev[1], v_prev[0])

            # Leg to Next
            v_next = np.array(pos[path[s_idx+1]]) - center_pos
            v_next = v_next / (np.linalg.norm(v_next) + 1e-9)
            ang_next = np.arctan2(v_next[1], v_next[0])

            # Get Current Computed Tangent (Flow: Prev -> Next)
            t_comp = path_data[p_idx][s_idx]

            # Add to circle
            # Store tuple: (angle, is_terminal, nat_vec, comp_outward_vec, other_nat_vec)
            # We store 'other_nat_vec' to define the triangle for this path later
            circle_entries.append({
                'angle': ang_prev, 'is_term': False,
                'nat': v_prev, 'comp': -t_comp, 'other': v_next,
                'pid': p_idx, 'sid': s_idx
            })
            circle_entries.append({
                'angle': ang_next, 'is_term': False,
                'nat': v_next, 'comp': t_comp, 'other': v_prev,
                'pid': p_idx, 'sid': s_idx
            })

        # 3b. Add Terminal Vectors
        terminal_entries = [] # Keep separate reference to iterate later
        for p_idx, s_idx in terminals:
            path = paths_indices[p_idx]
            # Neighbor index depends on start vs end
            neighbor_node = path[1] if s_idx == 0 else path[s_idx-1]
            v_out = np.array(pos[neighbor_node]) - center_pos
            v_out = v_out / (np.linalg.norm(v_out) + 1e-9)
            ang_out = np.arctan2(v_out[1], v_out[0])

            entry = {
                'angle': ang_out, 'is_term': True,
                'nat': v_out, 'comp': None, 'other': None,
                'pid': p_idx, 'sid': s_idx
            }
            circle_entries.append(entry)
            terminal_entries.append(entry)

        # Sort by angle
        circle_entries.sort(key=lambda x: x['angle'])

        N = len(circle_entries)
        if N < 2: continue
        def save_angle(target_vec, pid, sid):
            nm = np.linalg.norm(target_vec)
            if nm > 1e-9:
                target_vec = target_vec / nm
            else:
                target_vec = vec_p # Fallback
            # If terminal is Start (s=0), flow is Outward (v0->v1). Tangent = target_vec.
            # If terminal is End (s=n-1), flow is Inward (v_n-1 -> v_n). 
            if sid == 0:
                path_data[pid][sid] = target_vec
            else:
                path_data[pid][sid] = -target_vec

        angle_intervals = {}
        # 3c. Process each terminal
        for t_entry in terminal_entries:
            # Find index in sorted circle
            try:
                curr_idx = circle_entries.index(t_entry)
            except ValueError:
                continue

            # Find N_l (CCW neighbor that is NOT a terminal)
            # Scan backwards
            idx_l = (curr_idx - 1) % N
            while circle_entries[idx_l]['is_term'] and idx_l != curr_idx:
                idx_l = (idx_l - 1) % N

            # Find N_r (CW neighbor that is NOT a terminal)
            # Scan forwards
            idx_r = (curr_idx + 1) % N
            while circle_entries[idx_r]['is_term'] and idx_r != curr_idx:
                idx_r = (idx_r + 1) % N

            # If we circled back to self or didn't find non-terminals, skip
            if idx_l == curr_idx or idx_r == curr_idx:
                continue

            entry_l = circle_entries[idx_l]
            entry_r = circle_entries[idx_r]

            vec_p = t_entry['nat']
            pid = t_entry['pid']
            sid = t_entry['sid']

            # Neighbors' properties
            nl_nat = entry_l['nat']
            nl_comp = entry_l['comp']
            nl_other = entry_l['other'] # The other leg of the through path

            nr_nat = entry_r['nat']
            nr_comp = entry_r['comp']
            nr_other = entry_r['other']


            # --- Check Tangency Condition ---
            # If Nl and Nr are "tangent" (computed tangents oppose each other)
            # or if they are the exact same path/flow.
            # Dot product close to -1 means they are effectively a straight line flow.
            # dot_lr = np.dot(nl_comp, nr_comp)
            are_neighbors_tangent = (np.array_equal(
                nl_comp, nr_comp) or np.array_equal(
                nl_comp, - nr_comp)) and entry_l['pid'] != entry_r['pid']
            # are_neighbors_tangent = (dot_lr < -0.98) # Threshold for "Tangency"

            # if are_neighbors_tangent and entry_l['pid'] != entry_r['pid']:
            #      # Distinct paths forming a tangent line
            #      pass
            # elif entry_l['pid'] == entry_r['pid']:
            #      # Same path
            #      are_neighbors_tangent = True

            target_vec = None

            if are_neighbors_tangent:
                # Terminal must be tangent.
                # Project P onto the tangent line defined by neighbors.
                # Use Nl_comp as the reference axis.
                axis = nl_comp
                if np.dot(vec_p, axis) < 0:
                    axis = -axis
                target_vec = axis
            else:
                # --- Triangle Logic ---
                # Check containment
                # Triangle for L is defined by (nl_nat, nl_other)
                in_l = vec_inside_triangle(nl_nat, nl_other, vec_p)
                # Triangle for R is defined by (nr_nat, nr_other)
                in_r = vec_inside_triangle(nr_nat, nr_other, vec_p)

                if in_l and in_r:
                    # Don't touch (keep natural)
                    target_vec = vec_p
                elif in_l and not in_r:
                    # Between Nl_nat and Nr_comp
                    #store bisector as key
                    bisector = nl_nat+ nr_comp
                    angle_intervals.setdefault((tuple(nl_nat), tuple(nr_comp)), (bisector, []))[1].append((pid, sid, t_entry['angle'], vec_p))
                elif not in_l and in_r:
                    # Between Nl_comp and Nr_nat
                    bisector = nl_comp+ nr_nat
                    angle_intervals.setdefault((tuple(nl_comp), tuple(nr_nat)), (bisector, []))[1].append((pid, sid, t_entry['angle'], vec_p))
                else:
                    # Outside both: Between Nl_comp and Nr_comp
                    if entry_l['pid'] == entry_r['pid']:
                        #they must be tangent hence dot product of nl_comp, nr_comp is 0 -> need to detect sides
                        b = np.array([-nl_comp[1], nl_comp[0]])
                        bisector = -b if vec_inside_triangle(nl_nat, nr_nat, b) else b
                    else:
                        bisector = nl_comp+ nr_comp
                    angle_intervals.setdefault((tuple(nl_comp), tuple(nr_comp)), (bisector, []))[1].append((pid, sid, t_entry['angle'], vec_p))


            if target_vec is not None:
                save_angle(target_vec, pid, sid)

        def get_rel_angles(n):
            if terminal_angles_strategy == "random_random":
                s = "random" if random.random() < 0.5 or n ==1 else "center"
            else:
                s = terminal_angles_strategy
            if s == 'random':
                p = get_random_partition(-0.5, 0.5, n+1)[1:]
            elif s == 'center':
                p = [0.0 for _ in range(n)]
            else:
                p = np.linspace(-0.5, 0.5, num=n+2)[1:-1]
            return p

        for (l_vec, r_vec), (b, paths) in angle_intervals.items():
            max_a = np.arccos(np.clip(np.dot(l_vec, b), -1.0, 1.0))
            p = get_rel_angles(len(paths))

            # print("paths", p)
            #sort paths in this interval according to angle
            paths.sort(key = lambda x: x[2])
            for i, (pid, sid, _, _) in enumerate(paths):
                res = angle_interp(b, max_a, p[i])
                save_angle(res, pid, sid)


    # Convert to list of list of tuples
    result = []
    for p_vecs in path_data:
        result.append([tuple(v) for v in p_vecs])

    return result




def apply_tangent_overshoot(tangents, overshoot_radians):
    """
    Biases the tangent angle of start and end points in the opposite direction 
    of the path curvature (next/prev tangent).
    
    Args:
        tangents: List[List[Tuple]]. Modified in-place (or returned new).
        overshoot_radians: float (0 to pi/2).
    """
    if abs(overshoot_radians) < 1e-5:
        return tangents

    def rotate_vec(v, angle):
        c, s = np.cos(angle), np.sin(angle)
        return (v[0]*c - v[1]*s, v[0]*s + v[1]*c)

    for i in range(len(tangents)):
        path = list(tangents[i]) # Copy to modify
        n = len(path)
        if n < 2: continue

        # --- Start Node ---
        t0 = path[0]
        t1 = path[1]
        
        # Calculate angle difference
        ang0 = np.arctan2(t0[1], t0[0])
        ang1 = np.arctan2(t1[1], t1[0])
        diff = ang1 - ang0
        # Normalize -pi to pi
        diff = (diff + np.pi) % (2 * np.pi) - np.pi
        
        # If diff > 0 (turns left), rotate t0 right (negative)
        rot_dir = -1.0 if diff > 0 else 1.0
        path[0] = rotate_vec(t0, rot_dir * abs(overshoot_radians))

        # --- End Node ---
        tn = path[n-1]
        tn_prev = path[n-2]
        
        ang_n = np.arctan2(tn[1], tn[0])
        ang_prev = np.arctan2(tn_prev[1], tn_prev[0])
        diff = ang_n - ang_prev
        diff = (diff + np.pi) % (2 * np.pi) - np.pi
        
        # If diff > 0 (turns left), rotate tn right (negative)
        rot_dir = -1.0 if diff > 0 else 1.0
        path[n-1] = rotate_vec(tn, rot_dir * abs(overshoot_radians))
        
        tangents[i] = path

    return tangents


