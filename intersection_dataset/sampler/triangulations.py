def vec_inside_triangle(v1, v2, p):
    """
    Checks if vector p lies strictly inside the cone spanning v1 to v2 (shortest arc).
    Assumes unit vectors.
    """
    # p must be generated by positive linear combination a*v1 + b*v2
    # Determinant method:
    denom = v1[0] * v2[1] - v1[1] * v2[0]
    if abs(denom) < 1e-9:
        return False # Collinear legs, no triangle
        
    a = (p[0] * v2[1] - p[1] * v2[0]) / denom
    b = (v1[0] * p[1] - v1[1] * p[0]) / denom
    
    return a > 0 and b > 0

def triangulation_to_graph(tri: Delaunay, points, ignore_chull=False):
    """
    Converts a scipy Delaunay triangulation object into a NetworkX graph.
    """
    G = nx.Graph()

    # 1. Add nodes with their coordinates
    for i, pt in enumerate(points):
        if ignore_chull and not i in tri.convex_hull:
            G.add_node(i, pos=(pt[0], pt[1]))

    # 2. Add edges based on the simplices (triangles)
    # tri.simplices is an array of shape (ntri, 3) containing indices of points
    for simplex in tri.simplices:
        if ignore_chull and any(i in tri.convex_hull for i in simplex):
            continue
        # A simplex [p1, p2, p3] has edges (p1,p2), (p2,p3), (p3,p1)
        path = list(simplex)
        nx.add_path(G, path)
        # Close the loop (add edge between last and first)
        G.add_edge(path[-1], path[0])
    tmp = list(nx.isolates(G))
    G.remove_nodes_from(tmp)
    return G


def remove_prioritized_non_cut_edges(G: nx.Graph, n: int, seed=None):
    """
    Remove up to n edges from an undirected NetworkX graph without
    disconnecting it.

    Priority:
      1) edges (u, v) where both u and v currently have odd degree
         AND the edge is not a bridge
      2) any random non-bridge edge

    Stops early if no such edge exists.
    Modifies G in-place.
    """
    if seed is not None:
        random.seed(seed)

    for _ in range(n):
        if G.number_of_edges() == 0:
            return G

        # Compute bridges (edges whose removal would disconnect the graph)
        bridges = set(nx.bridges(G))

        # All removable edges (non-bridges)
        removable_edges = [
            (u, v) for u, v in G.edges()
            if (u, v) not in bridges and (v, u) not in bridges
        ]

        if not removable_edges:
            # No edge can be removed without disconnecting the graph
            break

        # Prioritize odd–odd degree edges among removable ones
        prioritized = [
            (u, v) for u, v in removable_edges
            if G.degree(u) % 2 == 1 and G.degree(v) % 2 == 1
        ]

        if prioritized:
            edge_to_remove = random.choice(prioritized)
        else:
            edge_to_remove = random.choice(removable_edges)

        G.remove_edge(*edge_to_remove)


