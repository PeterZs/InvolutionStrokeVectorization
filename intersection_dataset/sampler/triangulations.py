def merge_terminal_paths(paths: list[list]) -> list[list]:
    """
    Merges a list of paths (lists of integers) based on shared terminal nodes.
    
    Two paths are merged if:
    1. They share a common node that is a start or end in both paths.
    2. No third path uses that specific node (exclusive connection).
    
    The merging process repeats until no further merges are possible.
    
    Args:
        paths: A list of paths, where each path is a list of integers.
        
    Returns:
        A new list of merged paths.
    """
    # Create a copy to avoid modifying the input list in-place
    current_paths = [p[:] for p in paths]

    while True:
        merged_in_this_pass = False
        
        # 1. Build topology maps
        # count: How many times does a node appear in ALL paths (to check exclusivity)
        # terminals: Which paths end/start at a specific node
        node_counts = defaultdict(int)
        node_terminals = defaultdict(list)
        
        for idx, path in enumerate(current_paths):
            # Count global occurrences of every node
            for node in path:
                node_counts[tuple(node)] += 1
            
            # Map terminals
            if not len(path): continue
            
            start_node = path[0]
            end_node = path[-1]
            
            node_terminals[tuple(start_node)].append((idx, 'start'))
            
            # If path has length 1, start == end. 
            # We add it as 'end' as well to allow flexibility in matching direction,
            # though usually length-1 paths are just points.
            if len(path) > 1 or tuple(start_node) == tuple(end_node):
                # Avoid adding the same index twice for the same node if len > 1 
                # (unless it's a loop [1, 2, 1], which is handled by index check later)
                if len(path) > 1 and tuple(start_node) == tuple(end_node):
                    node_terminals[tuple(end_node)].append((idx, 'end'))
                elif tuple(start_node) != tuple(end_node) or len(path) == 1:
                     node_terminals[tuple(end_node)].append((idx, 'end'))

        # 2. Find a valid merge candidate
        merge_candidate = None
        
        for node, terms in node_terminals.items():
            # Criteria:
            # A. Node connects exactly two path endpoints (len(terms) == 2)
            # B. Node is not used anywhere else (node_counts[node] == 2)
            if len(terms) == 2 and node_counts[node] == 2:
                (idx1, type1), (idx2, type2) = terms
                
                # Ensure we aren't trying to merge a path to itself 
                # (This happens if a single path is a loop [1, 2, 1], start=1, end=1)
                if idx1 != idx2:
                    merge_candidate = (idx1, idx2, type1, type2)
                    break
        
        # 3. Execute Merge
        if merge_candidate:
            idx1, idx2, type1, type2 = merge_candidate
            p1 = current_paths[idx1]
            p2 = current_paths[idx2]
            
            new_path = []
            
            # Determine join orientation
            if type1 == 'end' and type2 == 'start':
                # Standard join: [A, B] + [B, C] -> [A, B, C]
                new_path = p1 + p2[1:]
            elif type1 == 'start' and type2 == 'end':
                # Reverse join: [B, C] + [A, B] -> [A, B, C]
                new_path = p2 + p1[1:]
            elif type1 == 'end' and type2 == 'end':
                # Tail-to-Tail: [A, B] + [C, B] -> [A, B, C]
                new_path = (p1 + p2[::-1][1:])
            elif type1 == 'start' and type2 == 'start':
                # Head-to-Head: [B, A] + [B, C] -> [A, B, C]
                new_path = p1[::-1] + p2[1:]
            
            # Rebuild path list: remove old two, add new one
            next_paths = []
            for i, p in enumerate(current_paths):
                if i != idx1 and i != idx2:
                    next_paths.append(p)
            next_paths.append(new_path)
            
            current_paths = next_paths
            merged_in_this_pass = True
        
        # If no merges occurred in this pass, we are done
        if not merged_in_this_pass:
            break
            
    return current_paths



def get_graph_statistics(
    paths: List[List[int]], 
    tangents: List[List[Tuple[int, ...]]], 
    N: int
) -> Dict[str, int]:
    """
    Calculates intersection statistics for degrees 3 to N.
    
    Definitions:
    - Degree: Sum of visits (Endpoint=1, Internal=2).
    - All Tangent: All incident vectors lie on the same line.
    - No Tangent: No two *distinct* paths share the same line direction.
      (Self-tangency of an internal path does not disqualify this metric).
    
    Returns:
        Flat dictionary with keys 'total_k', 'all_tangent_k', 'no_tangent_k'.
    """
    
    # 1. Initialize result dict with 0s for consistent CSV columns
    stats = {}
    for k in range(3, N + 1):
        stats[f'total_{k}'] = 0
    for k in range(3, N + 1):
        stats[f'all_tangent_{k}'] = 0
    for k in range(3, N + 1):
        stats[f'no_tangent_{k}'] = 0
    for k in range(3, N + 1):
        stats[f'terminal_{k}'] = 0

    # 2. Aggregate vectors and Path IDs by node
    # Key: Node ID
    # Value: List of tuples (path_index, vector)
    node_data = defaultdict(list)
    has_endpoint = set()
    
    for path_idx, path in enumerate(paths):
        path_tangents = tangents[path_idx]
        path_len = len(path)
        
        if path_len != len(path_tangents):
            continue 

        for i, node_id in enumerate(path):
            vec = path_tangents[i]
            
            # Check if this node is an endpoint of the path
            is_endpoint = (i == 0) or (i == path_len - 1)
            
            entry = (path_idx, vec)
            
            if is_endpoint:
                node_data[node_id].append(entry)
                has_endpoint.add(node_id)
            else:
                # Internal: Counts twice towards degree
                node_data[node_id].append(entry)
                node_data[node_id].append(entry)

    # Helper: Normalize vector to canonical direction
    def get_canonical(vec):
        for coord in vec:
            if coord > 0: return vec
            if coord < 0: return tuple(-x for x in vec)
        return vec

    # 3. Analyze nodes
    for node_id, items in node_data.items():
        k = len(items)
        
        # Filter: Only consider degrees between 3 and N
        if k < 3 or k > N:
            continue
            
        # Update Total Count
        stats[f'total_{k}'] += 1
        
        # Group Path IDs by Canonical Direction
        # Map: Canonical_Vector -> Set of Path IDs
        direction_map = defaultdict(set)
        
        for p_idx, vec in items:
            canon = get_canonical(vec)
            direction_map[canon].add(p_idx)
            
        num_unique_lines = len(direction_map)
        
        # --- Check: All Tangent ---
        # All vectors fall into exactly 1 canonical bucket
        if num_unique_lines == 1:
            stats[f'all_tangent_{k}'] += 1
            
        # --- Check: No Tangent ---
        # Condition: For every direction, it is owned by exactly 1 Path ID.
        # If any direction has set size > 1, it means two different paths are tangent.
        # Note: An internal path adds the same ID twice to a set, which collapses to size 1.
        
        is_no_tangent = True
        for path_set in direction_map.values():
            if len(path_set) > 1:
                is_no_tangent = False
                break
        
        if is_no_tangent:
            stats[f'no_tangent_{k}'] += 1
            
        stats[f'terminal_{k}'] += int(node_id in has_endpoint)

    return stats



