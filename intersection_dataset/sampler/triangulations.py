def rm_consecutive(arr: np.ndarray):
    diff_mask = np.ones(len(arr), dtype=bool)
    diff_mask[1:] = np.any(arr[1:] != arr[:-1], axis=1)
    return arr[diff_mask]

def sample_points_with_min_distance(n, w, h, min_dist, max_attempts=10000):
    """
    Samples n 2D points in a w x h grid such that each point is at least
    min_dist apart using a simple rejection sampling (dart throwing) method.
    """
    points = []
    attempts = 0

    while len(points) < n and attempts < max_attempts:
        # Generate a random candidate point
        candidate = np.random.rand(2) * [w, h]

        # Check distance against existing points
        if not points:
            points.append(candidate)
        else:
            # Calculate distances to all existing points
            existing_points = np.array(points)
            distances = np.linalg.norm(existing_points - candidate, axis=1)

            # If candidate is far enough from all existing points, accept it
            if np.all(distances >= min_dist):
                points.append(candidate)

        attempts += 1

    if len(points) < n:
        print(f"Warning: Only could fit {len(points)} points out of {n} requested "
              f"with minimum distance {min_dist}.")

    return np.array(points)

def vec_inside_triangle_angles(v_prev_u, v_next_u, d_vec_u):
    vecs_to_sort = [
                    (np.arctan2(v_prev_u[1], v_prev_u[0]), 'through'),
                    (np.arctan2(v_next_u[1], v_next_u[0]), 'through'),
                    (np.arctan2(d_vec_u[1], d_vec_u[0]), 'd')
                ]
    a, b = vecs_to_sort[0][0],  vecs_to_sort[1][0]
    angle = max(a, b)-min(a, b)
    # print("angle", math.degrees(angle))
